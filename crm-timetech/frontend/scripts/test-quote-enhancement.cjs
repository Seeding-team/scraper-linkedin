function load(relative) {
 const source = fs.readFileSync(path.join(__dirname, '..', relative), 'utf8');
 const js = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,jsx:ts.JsxEmit.ReactJSX}}).outputText;
 const module = {exports:{}};
 const resolve = name => name.startsWith('@/') ? load(name.slice(2) + '.ts') : name.startsWith('.') ? load(path.join(path.dirname(relative),name) + '.ts') : require(name);
 new Function('require','module','exports',js)(resolve,module,module.exports);
 return module.exports;
}
