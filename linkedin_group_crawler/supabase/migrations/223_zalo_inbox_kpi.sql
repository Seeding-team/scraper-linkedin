-- ==============================================================================
-- 223_zalo_inbox_kpi.sql
-- Chuan hoa tinh KPI Inbox Zalo (2 chieu + quy tac khoa chong trung 30 ngay +
-- auto-match khach tu Post Feed / Seeding), tach biet nghiep vu chia se chat
-- (zalo_conversation_permissions) voi bang ghi nhan KPI (zalo_inbox_kpi).
-- ==============================================================================

-- 1. Bang chinh zalo_inbox_kpi
CREATE TABLE IF NOT EXISTS public.zalo_inbox_kpi (
    id                      BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_member               UUID        REFERENCES public.app_users(id) ON DELETE SET NULL,
    id_leader               UUID        REFERENCES public.app_users(id) ON DELETE SET NULL,
    account_id              TEXT        NOT NULL,
    conversation_id         TEXT,
    phone_number            TEXT,
    source_type             TEXT        NOT NULL DEFAULT 'direct_inbox',
        -- 'post_feed_outbound' | 'post_feed_inbound' | 'direct_inbox' | 'legacy_verified'
    source_platform         TEXT,
        -- 'facebook' | 'linkedin' | 'threads' | 'youtube' | null
    source_post_id          TEXT,
    source_post_url         TEXT,
    direction_status        TEXT        NOT NULL DEFAULT 'outbound_sent',
        -- 'outbound_sent' | 'inbound_pending' | 'two_way' | 'inbound_replied' | 'manual_verified'
    is_confirmed            BOOLEAN     NOT NULL DEFAULT FALSE,
    is_lead                 BOOLEAN     NOT NULL DEFAULT FALSE,
    first_outbound_at       TIMESTAMPTZ,
    first_customer_msg_at   TIMESTAMPTZ,
    first_staff_reply_at    TIMESTAMPTZ,
    confirmed_at            TIMESTAMPTZ,
    verified_by             UUID        REFERENCES public.app_users(id) ON DELETE SET NULL,
    note                    TEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes toi uu & chong duplicate pending row
CREATE UNIQUE INDEX IF NOT EXISTS uq_zalo_inbox_kpi_pending_conv
    ON public.zalo_inbox_kpi (account_id, conversation_id)
    WHERE conversation_id IS NOT NULL AND is_confirmed = FALSE;

CREATE INDEX IF NOT EXISTS idx_zalo_inbox_kpi_member_confirmed
    ON public.zalo_inbox_kpi (id_member, confirmed_at DESC)
    WHERE is_confirmed = TRUE AND id_member IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_zalo_inbox_kpi_day_vn
    ON public.zalo_inbox_kpi (id_member, ((confirmed_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::date))
    WHERE is_confirmed = TRUE AND confirmed_at IS NOT NULL AND id_member IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_zalo_inbox_kpi_phone_confirmed
    ON public.zalo_inbox_kpi (phone_number, is_confirmed, confirmed_at DESC)
    WHERE phone_number IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_zalo_inbox_kpi_account_conv
    ON public.zalo_inbox_kpi (account_id, conversation_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_zalo_inbox_kpi_post_id
    ON public.zalo_inbox_kpi (source_post_id)
    WHERE source_post_id IS NOT NULL;

-- RLS & Grants (an toan tren moi phien ban PostgreSQL)
ALTER TABLE public.zalo_inbox_kpi ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS zalo_inbox_kpi_select ON public.zalo_inbox_kpi;
CREATE POLICY zalo_inbox_kpi_select ON public.zalo_inbox_kpi
    FOR SELECT USING (true);

DROP POLICY IF EXISTS zalo_inbox_kpi_insert ON public.zalo_inbox_kpi;
CREATE POLICY zalo_inbox_kpi_insert ON public.zalo_inbox_kpi
    FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS zalo_inbox_kpi_update ON public.zalo_inbox_kpi;
CREATE POLICY zalo_inbox_kpi_update ON public.zalo_inbox_kpi
    FOR UPDATE USING (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.zalo_inbox_kpi TO service_role, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.zalo_inbox_kpi_id_seq TO service_role, authenticated;

COMMENT ON TABLE public.zalo_inbox_kpi IS
    'Luu tru KPI Inbox Zalo 2 chieu, theo doi hoi thoai xuat phat tu Post Feed hoac Inbox truc tiep va chong trung 30 ngay.';

-- 2. Backfill idempotent tu cac hoi thoai Zalo da verify trong zalo_conversation_permissions
INSERT INTO public.zalo_inbox_kpi (
    id_member,
    id_leader,
    account_id,
    conversation_id,
    source_type,
    direction_status,
    is_confirmed,
    is_lead,
    confirmed_at,
    verified_by,
    note,
    created_at,
    updated_at
)
SELECT DISTINCT ON (z.account_id, z.conversation_id)
    z.id_member,
    CASE
        WHEN z.id_leader IS NOT NULL
         AND EXISTS (SELECT 1 FROM public.app_users ul WHERE ul.id = z.id_leader)
        THEN z.id_leader
        ELSE NULL
    END                                       AS id_leader,
    z.account_id,
    z.conversation_id,
    'legacy_verified'                         AS source_type,
    'manual_verified'                         AS direction_status,
    TRUE                                      AS is_confirmed,
    COALESCE(z.is_lead, FALSE)                AS is_lead,
    z.verified_at                             AS confirmed_at,
    CASE
        WHEN z.verified_by ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
         AND EXISTS (SELECT 1 FROM public.app_users uv WHERE uv.id = z.verified_by::uuid)
        THEN z.verified_by::uuid
        ELSE NULL
    END                                       AS verified_by,
    z.note,
    COALESCE(z.created_at, z.verified_at)     AS created_at,
    COALESCE(z.updated_at, z.verified_at)     AS updated_at
FROM public.zalo_conversation_permissions z
WHERE z.shared_role = 'leader'
  AND z.is_active = TRUE
  AND z.is_verify = TRUE
  AND z.verified_at IS NOT NULL
  AND z.id_member IS NOT NULL
  AND EXISTS (SELECT 1 FROM public.app_users um WHERE um.id = z.id_member)
  AND NOT EXISTS (
      SELECT 1
      FROM public.zalo_inbox_kpi k
      WHERE k.account_id = z.account_id
        AND k.conversation_id = z.conversation_id
        AND k.is_confirmed = TRUE
  )
ORDER BY z.account_id, z.conversation_id, z.verified_at ASC;

-- 3. View tong hop KPI Inbox Zalo theo member x ngay VN
CREATE OR REPLACE VIEW public.v_member_daily_zalo_inbox AS
SELECT
    k.id_member,
    (k.confirmed_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::date AS day_vn,
    COUNT(*)::int                                           AS inbox_count,
    COUNT(*) FILTER (WHERE k.is_lead)::int                  AS lead_count
FROM public.zalo_inbox_kpi k
WHERE k.is_confirmed = TRUE
  AND k.confirmed_at IS NOT NULL
  AND k.id_member IS NOT NULL
GROUP BY k.id_member, (k.confirmed_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::date;

COMMENT ON VIEW public.v_member_daily_zalo_inbox IS
    'Aggregated confirmed Zalo inbox KPI and Zalo leads per member per VN-day from zalo_inbox_kpi';

-- 4. Nang cap RPC get_team_kpi_overview dung v_member_daily_zalo_inbox
CREATE OR REPLACE FUNCTION public.get_team_kpi_overview(
    p_leader_email TEXT DEFAULT NULL,
    p_id_team      TEXT DEFAULT NULL,
    p_start        TEXT DEFAULT NULL,
    p_end          TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
AS $$
DECLARE
    v_leader_id UUID;
    v_start DATE := COALESCE(p_start::date, (CURRENT_DATE - EXTRACT(DOW FROM CURRENT_DATE)::int));
    v_end   DATE := COALESCE(p_end::date,   v_start + 6);
    v_team_ids UUID[];
    v_member_ids UUID[];
    v_result JSONB;
BEGIN
    IF p_leader_email IS NOT NULL AND p_leader_email <> '' THEN
        SELECT id INTO v_leader_id FROM public.app_users
        WHERE LOWER(email) = LOWER(TRIM(p_leader_email))
        LIMIT 1;
    END IF;

    IF p_id_team IS NOT NULL AND p_id_team <> '' THEN
        v_team_ids := ARRAY[p_id_team::uuid];
    ELSIF v_leader_id IS NOT NULL THEN
        SELECT COALESCE(ARRAY_AGG(id), ARRAY[]::uuid[])
        INTO v_team_ids
        FROM public.teams
        WHERE id_leader = v_leader_id;
    ELSE
        SELECT COALESCE(ARRAY_AGG(id), ARRAY[]::uuid[])
        INTO v_team_ids
        FROM public.teams;
    END IF;

    IF v_team_ids IS NULL OR array_length(v_team_ids, 1) IS NULL THEN
        RETURN jsonb_build_object('totals', '{}'::jsonb, 'members', '[]'::jsonb);
    END IF;

    SELECT COALESCE(ARRAY_AGG(DISTINCT id_member), ARRAY[]::uuid[])
    INTO v_member_ids
    FROM public.member_of_teams
    WHERE id_teams = ANY(v_team_ids);

    IF v_leader_id IS NOT NULL AND NOT (v_leader_id = ANY(v_member_ids)) THEN
        v_member_ids := array_append(v_member_ids, v_leader_id);
    END IF;

    IF array_length(v_member_ids, 1) IS NULL THEN
        RETURN jsonb_build_object('totals', '{}'::jsonb, 'members', '[]'::jsonb);
    END IF;

    SELECT jsonb_build_object(
        'totals', (
            WITH kpi_agg AS (
                SELECT
                    COALESCE(SUM(kpi_inbox)::numeric,   0) AS inbox_target,
                    COALESCE(SUM(kpi_lead)::numeric,    0) AS lead_target,
                    COALESCE(SUM(COALESCE(kpi_call, kpi_post))::numeric, 0) AS call_target,
                    COALESCE(SUM(kpi_post)::numeric,    0) AS post_target,
                    COALESCE(SUM(kpi_comment)::numeric, 0) AS comment_target
                FROM public.kpi_tracker
                WHERE id_member = ANY(v_member_ids)
                  AND status = 'active'
                  AND start_date::date = v_start
                  AND end_date::date   = v_end
            ),
            seed_agg AS (
                SELECT COALESCE(SUM(verified_count)::numeric, 0) AS comment_actual
                FROM public.v_member_daily_seeding
                WHERE id_member = ANY(v_member_ids)
                  AND day BETWEEN v_start AND v_end
            ),
            fb_inbox_agg AS (
                SELECT
                    COALESCE(SUM(inbox_count)::numeric, 0) AS inbox_actual_fb,
                    COALESCE(SUM(lead_count)::numeric,  0) AS lead_actual_fb
                FROM public.v_member_daily_fb_inbox
                WHERE id_member = ANY(v_member_ids)
                  AND day_vn BETWEEN v_start AND v_end
            ),
            call_agg AS (
                SELECT
                    COALESCE(SUM(call_count)::numeric, 0) AS call_actual,
                    COALESCE(SUM(call_attempts)::numeric, 0) AS call_attempts_actual
                FROM public.v_member_daily_calls
                WHERE id_member = ANY(v_member_ids)
                  AND day_vn BETWEEN v_start AND v_end
            ),
            zalo_agg AS (
                SELECT
                    COALESCE(SUM(inbox_count)::numeric, 0) AS inbox_actual_zalo,
                    COALESCE(SUM(lead_count)::numeric,  0) AS lead_actual_zalo
                FROM public.v_member_daily_zalo_inbox
                WHERE id_member = ANY(v_member_ids)
                  AND day_vn BETWEEN v_start AND v_end
            )
            SELECT jsonb_build_object(
                'member_count',      array_length(v_member_ids, 1),
                'inbox_target',      kpi_agg.inbox_target,
                'lead_target',       kpi_agg.lead_target,
                'call_target',       kpi_agg.call_target,
                'post_target',       kpi_agg.call_target,
                'comment_target',    kpi_agg.comment_target,
                'inbox_actual_zalo', zalo_agg.inbox_actual_zalo,
                'lead_actual_zalo',  zalo_agg.lead_actual_zalo,
                'inbox_actual_fb',   fb_inbox_agg.inbox_actual_fb,
                'lead_actual_fb',    fb_inbox_agg.lead_actual_fb,
                'call_actual',       call_agg.call_actual,
                'call_attempts',     call_agg.call_attempts_actual,
                'post_actual',       call_agg.call_actual,
                'comment_actual',    seed_agg.comment_actual
            )
            FROM kpi_agg, seed_agg, fb_inbox_agg, call_agg, zalo_agg
        ),
        'members', COALESCE((
            SELECT jsonb_agg(row_to_json(t))
            FROM (
                SELECT
                    u.id::text AS id,
                    LOWER(u.email) AS email,
                    u.name,
                    COALESCE(u.role, 'member') AS role,
                    jsonb_build_object(
                        'kpi_call',    COALESCE(kt.kpi_call, kt.kpi_post, 0),
                        'kpi_post',    COALESCE(kt.kpi_call, kt.kpi_post, 0),
                        'kpi_lead',    COALESCE(kt.kpi_lead,    0),
                        'kpi_inbox',   COALESCE(kt.kpi_inbox,   0),
                        'kpi_comment', COALESCE(kt.kpi_comment, 0),
                        'start_date',  kt.start_date,
                        'end_date',    kt.end_date
                    ) AS kpi,
                    jsonb_build_object(
                        'comment',          COALESCE(s.verified_count, 0),
                        'call',             COALESCE(c.call_count, 0),
                        'call_attempts',    COALESCE(c.call_attempts, 0),
                        'post',             COALESCE(c.call_count, 0),
                        'inbox_zalo',       COALESCE(z.inbox_count, 0),
                        'lead_zalo',        COALESCE(z.lead_count, 0),
                        'inbox_fb_kpi',     COALESCE(f.inbox_count, 0),
                        'lead_fb_kpi',      COALESCE(f.lead_count, 0)
                    ) AS actuals
                FROM public.app_users u
                LEFT JOIN public.kpi_tracker kt
                       ON kt.id_member = u.id AND kt.status = 'active'
                      AND kt.start_date::date = v_start
                      AND kt.end_date::date   = v_end
                LEFT JOIN (
                    SELECT id_member, SUM(verified_count)::int AS verified_count
                    FROM public.v_member_daily_seeding
                    WHERE id_member = ANY(v_member_ids)
                      AND day BETWEEN v_start AND v_end
                    GROUP BY id_member
                ) s ON s.id_member = u.id
                LEFT JOIN (
                    SELECT id_member, SUM(inbox_count)::int AS inbox_count,
                                     SUM(lead_count)::int AS lead_count
                    FROM public.v_member_daily_fb_inbox
                    WHERE id_member = ANY(v_member_ids)
                      AND day_vn BETWEEN v_start AND v_end
                    GROUP BY id_member
                ) f ON f.id_member = u.id
                LEFT JOIN (
                    SELECT id_member,
                           SUM(call_count)::int AS call_count,
                           SUM(call_attempts)::int AS call_attempts
                    FROM public.v_member_daily_calls
                    WHERE id_member = ANY(v_member_ids)
                      AND day_vn BETWEEN v_start AND v_end
                    GROUP BY id_member
                ) c ON c.id_member = u.id
                LEFT JOIN (
                    SELECT id_member,
                           SUM(inbox_count)::int AS inbox_count,
                           SUM(lead_count)::int  AS lead_count
                    FROM public.v_member_daily_zalo_inbox
                    WHERE id_member = ANY(v_member_ids)
                      AND day_vn BETWEEN v_start AND v_end
                    GROUP BY id_member
                ) z ON z.id_member = u.id
                WHERE u.id = ANY(v_member_ids)
                ORDER BY u.email NULLS LAST
            ) t
        ), '[]'::jsonb),
        'range', jsonb_build_object('start', v_start, 'end', v_end)
    )
    INTO v_result;

    RETURN v_result;
END;
$$;

COMMENT ON FUNCTION public.get_team_kpi_overview IS
    'Tra JSON tong hop KPI cua team theo 4 tru cot: CMT, INBOX (FB + Zalo 2 chieu), CALL, LEAD.';

-- 5. Nang cap RPC get_admin_teams_kpi_overview dung v_member_daily_zalo_inbox
CREATE OR REPLACE FUNCTION public.get_admin_teams_kpi_overview(
    p_start DATE DEFAULT NULL,
    p_end   DATE DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
AS $$
DECLARE
    v_start DATE := COALESCE(
        p_start,
        (CURRENT_DATE - EXTRACT(DOW FROM CURRENT_DATE)::int)
    );
    v_end DATE := COALESCE(p_end, v_start + 6);
BEGIN
    RETURN jsonb_build_object(
        'teams', COALESCE((
            SELECT jsonb_agg(row_to_json(t) ORDER BY t.name_team)
            FROM (
                SELECT
                    tm.id::text                       AS id,
                    tm.name_team,
                    tm.team_type,
                    tm.id_leader::text                AS id_leader,
                    tm.leader_member_id::text          AS leader_member_id,
                    COALESCE(lu.email, '')            AS leader_email,
                    COALESCE(lu.name, lm.display_name, lm.full_name, '') AS leader_name,
                    (tm.id_leader IS NOT NULL)        AS leader_linked,
                    COALESCE((
                        SELECT jsonb_agg(jsonb_build_object(
                            'id',    mu.id::text,
                            'email', mu.email,
                            'name',  COALESCE(mu.name, '')
                        ) ORDER BY mu.email)
                        FROM public.member_of_teams mot2
                        JOIN public.app_users mu ON mu.id = mot2.id_member
                        WHERE mot2.id_teams = tm.id
                    ), '[]'::jsonb)                   AS members,
                    COALESCE((
                        SELECT COUNT(*)
                        FROM public.member_of_teams mot3
                        WHERE mot3.id_teams = tm.id
                    ), 0)                             AS number_of_member
                FROM public.teams tm
                LEFT JOIN public.app_users lu ON lu.id = tm.id_leader
                LEFT JOIN public.members lm ON lm.id = tm.leader_member_id
            ) t
        ), '[]'::jsonb),

        'kpi_data', COALESCE((
            SELECT jsonb_agg(row_to_json(t) ORDER BY t.team_name, t.is_leader DESC, t.member_email)
            FROM (
                SELECT
                    p.team_id                                         AS team_id,
                    p.team_name                                       AS team_name,
                    p.leader_email                                    AS leader_email,
                    p.person_id::text                                 AS member_id,
                    p.person_email                                    AS member_email,
                    p.person_name                                     AS member_name,
                    p.is_leader                                       AS is_leader,
                    COALESCE(kt.kpi_call, kt.kpi_post, 0)             AS kpi_call,
                    COALESCE(kt.kpi_call, kt.kpi_post, 0)             AS kpi_post,
                    COALESCE(kt.kpi_lead, 0)                          AS kpi_lead,
                    COALESCE(kt.kpi_inbox, 0)                         AS kpi_inbox,
                    COALESCE(kt.kpi_comment, 0)                       AS kpi_comment,
                    COALESCE(s.verified_count, 0)                     AS verified_count,
                    COALESCE(cl.call_count, 0)                        AS call_count,
                    COALESCE(cl.call_count, 0)                        AS post_count,
                    COALESCE(fb.inbox_count, 0)                       AS inbox_count,
                    COALESCE(fb.lead_count, 0)                        AS lead_count,
                    COALESCE(cl.call_count, 0)                        AS kpi_call_current,
                    COALESCE(cl.call_count, 0)                        AS kpi_post_current,
                    COALESCE(fb.inbox_count, 0)                       AS kpi_inbox_current,
                    COALESCE(fb.lead_count, 0)                        AS kpi_lead_current,
                    jsonb_build_object(
                        'start', v_start,
                        'end',   v_end
                    )                                                 AS kpi_inbox_range
                FROM (
                    SELECT
                        tm.id                              AS team_id_raw,
                        tm.id::text                         AS team_id,
                        tm.name_team                        AS team_name,
                        COALESCE(leader.email, '')          AS leader_email,
                        mu.id                                AS person_id,
                        mu.email                             AS person_email,
                        COALESCE(mu.name, mu.email)          AS person_name,
                        false                                AS is_leader
                    FROM public.teams tm
                    LEFT JOIN public.app_users leader ON leader.id = tm.id_leader
                    JOIN public.member_of_teams mot ON mot.id_teams = tm.id
                    JOIN public.app_users mu ON mu.id = mot.id_member

                    UNION ALL

                    SELECT
                        tm.id                              AS team_id_raw,
                        tm.id::text                         AS team_id,
                        tm.name_team                        AS team_name,
                        leader.email                         AS leader_email,
                        leader.id                            AS person_id,
                        leader.email                         AS person_email,
                        COALESCE(leader.name, leader.email)  AS person_name,
                        true                                 AS is_leader
                    FROM public.teams tm
                    JOIN public.app_users leader ON leader.id = tm.id_leader
                ) p
                LEFT JOIN LATERAL (
                    SELECT kt2.kpi_call, kt2.kpi_post, kt2.kpi_lead, kt2.kpi_inbox, kt2.kpi_comment
                    FROM public.kpi_tracker kt2
                    WHERE kt2.id_member = p.person_id
                      AND kt2.status = 'active'
                      AND kt2.start_date::date <= v_end
                      AND kt2.end_date::date   >= v_start
                    ORDER BY
                        (kt2.id_team = p.team_id_raw) DESC NULLS LAST,
                        kt2.updated_at DESC
                    LIMIT 1
                ) kt ON TRUE
                LEFT JOIN (
                    SELECT id_member, SUM(verified_count)::int AS verified_count
                    FROM public.v_member_daily_seeding
                    WHERE day BETWEEN v_start AND v_end
                    GROUP BY id_member
                ) s ON s.id_member = p.person_id
                LEFT JOIN (
                    SELECT id_member, SUM(call_count)::int AS call_count
                    FROM public.v_member_daily_calls
                    WHERE day_vn BETWEEN v_start AND v_end
                    GROUP BY id_member
                ) cl ON cl.id_member = p.person_id
                LEFT JOIN (
                    SELECT id_member,
                           SUM(inbox_count)::int AS inbox_count,
                           SUM(lead_count)::int  AS lead_count
                    FROM (
                        SELECT id_member, inbox_count, 0 AS lead_count
                        FROM public.v_member_daily_fb_inbox
                        WHERE day_vn BETWEEN v_start AND v_end
                        UNION ALL
                        SELECT id_member, 0 AS inbox_count, lead_count
                        FROM public.v_member_daily_fb_lead
                        WHERE day_vn BETWEEN v_start AND v_end
                        UNION ALL
                        SELECT id_member, inbox_count, lead_count
                        FROM public.v_member_daily_zalo_inbox
                        WHERE day_vn BETWEEN v_start AND v_end
                    ) x
                    GROUP BY id_member
                ) fb ON fb.id_member = p.person_id
            ) t
        ), '[]'::jsonb),

        'range', jsonb_build_object('start', v_start, 'end', v_end)
    );
END;
$$;

COMMENT ON FUNCTION public.get_admin_teams_kpi_overview IS
    'Admin teams-management RPC ho tro KPI Call thay Post va Zalo Inbox 2 chieu (zalo_inbox_kpi).';

